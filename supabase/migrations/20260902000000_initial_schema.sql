-- ============================================================================
-- OpenNotepad — Migration 0001: Initial schema (Phase 1)
--
-- Creates the `profiles` and `notes` tables with Row Level Security.
--
-- Security notes:
--   * The anonymous role gets NO insert/update/delete grants on `notes` —
--     all guest writes will go through SECURITY DEFINER RPCs (Phase 2+).
--   * `notes.edit_code_hash` is excluded from column-level grants reachable
--     by anon/authenticated roles. Only SECURITY DEFINER functions may touch
--     it (added in Phase 2).
--   * `profiles.is_admin` cannot be updated by any non-admin grant; it is
--     managed by database operators only.
-- ============================================================================

-- ----------------------------------------------------------------------------
-- profiles: one row per auth user
-- ----------------------------------------------------------------------------
create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  username text unique,
  display_name text,
  avatar_url text,
  is_admin boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- ----------------------------------------------------------------------------
-- notes: every note, guest or owned
-- ----------------------------------------------------------------------------
create table public.notes (
  id uuid primary key default gen_random_uuid(),
  -- 7-character cryptographically random, non-sequential id (generated by the
  -- app / RPCs from Phase 2 onward).
  public_id text not null unique,
  owner_id uuid references public.profiles (id) on delete set null,
  custom_slug text unique,
  title text not null default '',
  content jsonb not null default '{"type": "doc", "content": []}'::jsonb,
  content_format text not null default 'tiptap_json'
    check (content_format in ('tiptap_json', 'markdown', 'plain_text')),
  -- bcrypt hash (pgcrypto, Phase 2). Raw edit codes are never stored.
  edit_code_hash text,
  visibility text not null default 'public'
    check (visibility in ('public', 'private')),
  editing_policy text not null default 'edit_code'
    check (editing_policy in ('edit_code', 'account', 'read_only')),
  expires_at timestamptz,
  deleted_at timestamptz,
  favorite boolean not null default false,
  revision_no integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index notes_owner_id_idx on public.notes (owner_id);
create index notes_updated_at_idx on public.notes (updated_at desc);

-- ----------------------------------------------------------------------------
-- updated_at maintenance trigger
-- ----------------------------------------------------------------------------
create function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger profiles_set_updated_at
  before update on public.profiles
  for each row
  execute function public.set_updated_at();

create trigger notes_set_updated_at
  before update on public.notes
  for each row
  execute function public.set_updated_at();

-- ----------------------------------------------------------------------------
-- Auto-create a profile whenever a user signs up
-- ----------------------------------------------------------------------------
create function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id)
  values (new.id)
  on conflict (id) do nothing;
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row
  execute function public.handle_new_user();

-- ----------------------------------------------------------------------------
-- Row Level Security
-- ----------------------------------------------------------------------------
alter table public.profiles enable row level security;
alter table public.notes enable row level security;

-- profiles: least privilege. Users see and manage only their own profile;
-- `is_admin` is not updatable through any client-reachable grant.
revoke all on public.profiles from anon, authenticated;
grant select on public.profiles to authenticated;
grant update (username, display_name, avatar_url) on public.profiles to authenticated;

create policy "profiles_select_own"
  on public.profiles for select to authenticated
  using (auth.uid() = id);

create policy "profiles_insert_own"
  on public.profiles for insert to authenticated
  with check (auth.uid() = id);

create policy "profiles_update_own"
  on public.profiles for update to authenticated
  using (auth.uid() = id)
  with check (auth.uid() = id);

-- notes: grants. The anonymous role must never get INSERT/UPDATE/DELETE
-- grants — guest writes go through SECURITY DEFINER RPCs (Phase 2+).
-- edit_code_hash is deliberately absent from every column list below.
revoke all on public.notes from anon, authenticated;

grant select (
  id, public_id, owner_id, custom_slug, title, content, content_format,
  visibility, editing_policy, expires_at, deleted_at, favorite,
  revision_no, created_at, updated_at
) on public.notes to anon, authenticated;

grant insert (
  id, public_id, owner_id, custom_slug, title, content, content_format,
  visibility, editing_policy, expires_at, favorite
) on public.notes to authenticated;

grant update (
  public_id, custom_slug, title, content, content_format,
  visibility, editing_policy, expires_at, deleted_at, favorite
) on public.notes to authenticated;

grant delete on public.notes to authenticated;

create policy "notes_select_public"
  on public.notes for select to anon, authenticated
  using (
    visibility = 'public'
    and deleted_at is null
    and (expires_at is null or expires_at > now())
  );

create policy "notes_select_own"
  on public.notes for select to authenticated
  using (owner_id is not null and owner_id = auth.uid());

create policy "notes_insert_own"
  on public.notes for insert to authenticated
  with check (owner_id = auth.uid());

create policy "notes_update_own"
  on public.notes for update to authenticated
  using (owner_id = auth.uid())
  with check (owner_id = auth.uid());

create policy "notes_delete_own"
  on public.notes for delete to authenticated
  using (owner_id = auth.uid());
